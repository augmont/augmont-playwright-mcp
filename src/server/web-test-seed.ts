function page(id: string, label: string, path: string): WebFlowStep[] {
  return [
    { id, label: `Open ${label}`, action: 'goto', url: path },
    { id: `${id}-url`, label: `${label} URL`, action: 'assertUrl', url: path },
  ];
}

function buyerLogin(): WebFlowStep {
  return { id: 'login', label: 'Login as buyer', action: 'loginRole', value: 'buyer' };
}

function adminLogin(): WebFlowStep {
  return { id: 'login', label: 'Login as admin', action: 'loginRole', value: 'admin' };
}

